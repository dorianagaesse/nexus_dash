import { expect, test } from "@playwright/test";
import { signInAsVerifiedUser } from "./helpers/auth-helpers";
import { createProjectFromProjectsPage, openNewestProjectDashboard, uniqueProjectName } from "./helpers/project-helpers";

test("owner controls agent Done moves per project without changing human moves", async ({ page }) => {
  await signInAsVerifiedUser(page);
  const name = uniqueProjectName("nd449");
  await createProjectFromProjectsPage(page, name);
  await openNewestProjectDashboard(page, name);
  const projectId = page.url().match(/\/projects\/([^/?#]+)/)![1];
  const taskResponse = await page.request.post(`/api/projects/${projectId}/tasks`, { data: { title: "Policy test" } });
  expect(taskResponse.ok()).toBeTruthy();
  const { task } = await taskResponse.json();
  const path = `/api/projects/${projectId}/tasks/${task.id}/status`;
  await page.getByRole("button", { name: "Share project" }).click();
  await page.getByRole("button", { name: "Agent access", exact: true }).click();
  const toggle = page.getByRole("switch", { name: "Allow agents to move tasks to Done" });
  await expect(toggle).not.toBeChecked();
  await expect(toggle).toBeEnabled();
  await page.locator("#project-agent-label").fill("Policy bot");
  await page.getByRole("button", { name: "Create credential", exact: true }).click();
  const key = page.getByRole("textbox", { name: "API key for Policy bot", exact: true });
  await expect(key).toBeVisible();
  const exchange = await page.request.post("/api/auth/agent/token", { headers: { Authorization: `ApiKey ${await key.inputValue()}` } });
  expect(exchange.ok()).toBeTruthy();
  const { accessToken } = await exchange.json();
  const headers = { Authorization: `Bearer ${accessToken}` };
  await page.getByRole("button", { name: "Hide key", exact: true }).click();
  const denied = await page.request.post(path, { headers, data: { status: "Done" } });
  expect(denied.status()).toBe(403);
  expect(await denied.json()).toEqual({ error: "agent-done-move-disabled" });
  const bulkPath = `/api/projects/${projectId}/tasks/reorder`;
  const columns = [{ status: "Done", taskIds: [task.id] }];
  const bulkDenied = await page.request.post(bulkPath, { headers, data: { columns } });
  expect(bulkDenied.status()).toBe(403);
  const current = await page.request.get(`/api/projects/${projectId}/tasks`);
  expect((await current.json()).tasks.find((entry: { id: string }) => entry.id === task.id).status).toBe("Backlog");
  expect((await page.request.post(path, { data: { status: "Done" } })).ok()).toBeTruthy();
  expect((await page.request.post(path, { data: { status: "Backlog" } })).ok()).toBeTruthy();
  await toggle.click();
  await expect(toggle).toBeChecked();
  await expect(page.getByText("Agent capabilities saved.", { exact: true })).toBeVisible();
  await expect(toggle).toBeEnabled();
  const secondProject = await page.request.post("/api/projects", { data: { name: uniqueProjectName("nd449-other") } });
  expect(secondProject.ok()).toBeTruthy();
  const otherProject = (await secondProject.json()).project;
  const otherSettings = await page.request.get(`/api/projects/${otherProject.id}/agent-access`);
  expect((await otherSettings.json()).agentCanMoveTasksToDone).toBe(false);
  await page.screenshot({ path: "test-results/nd449-desktop.png", fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: "test-results/nd449-mobile.png", fullPage: true });
  expect((await page.request.post(path, { headers, data: { status: "Done" } })).ok()).toBeTruthy();
  expect((await page.request.post(path, { data: { status: "Backlog" } })).ok()).toBeTruthy();
  expect((await page.request.post(bulkPath, { headers, data: { columns } })).ok()).toBeTruthy();
  await page.reload();
  await page.getByRole("button", { name: "Share project" }).click();
  await page.getByRole("button", { name: "Agent access", exact: true }).click();
  await expect(toggle).toBeChecked();
  await toggle.click();
  await expect(toggle).not.toBeChecked();
  await expect(toggle).toBeEnabled();
  expect((await page.request.post(path, { data: { status: "Backlog" } })).ok()).toBeTruthy();
  expect((await page.request.post(path, { headers, data: { status: "Done" } })).status()).toBe(403);
  expect((await page.request.patch(`/api/projects/${projectId}/agent-access`, { headers, data: { agentCanMoveTasksToDone: true } })).status()).toBe(401);
});
